"""Latency-realistic fake model for LOAD TESTING THE PLATFORM (not the model).

Behaves like a tool-using assistant: ~half the turns call a tool first (two model calls), each call sleeps for a
lognormal latency with configurable median. Lets us measure SupportPilot's own capacity independent of provider
quota/latency. Enable with LLM_PROVIDER=simulated (SIM_LLM_MEDIAN_SECONDS, SIM_LLM_TOOL_RATE).
"""
from __future__ import annotations

import asyncio
import math
import random
import uuid
from typing import Any

from .base import LLMResponse, ToolCall


class SimulatedLLM:
    # Tool mix when a tool is used: mirrors production (mostly KB search, some orders, a few tickets).
    MIX = (("search_knowledge_base", 0.70), ("get_order_status", 0.15), ("list_my_orders", 0.07), ("create_support_ticket", 0.08))

    def __init__(self, median_seconds: float = 2.5, sigma: float = 0.4, tool_rate: float = 0.6, seed: int | None = None) -> None:
        self.mu, self.sigma, self.tool_rate = math.log(median_seconds), sigma, tool_rate
        self.rng = random.Random(seed)

    def _pick_tool(self, offered: set[str], text: str) -> tuple[str, dict[str, Any]]:
        names = [(n, w) for n, w in self.MIX if n in offered] or [("search_knowledge_base", 1.0)]
        name = self.rng.choices([n for n, _ in names], [w for _, w in names])[0]
        args: dict[str, Any] = {
            "search_knowledge_base": {"query": text[:200]},
            "get_order_status": {"order_id": self.rng.choice(["ACM-1001", "ACM-1002", "ACM-2001", "ACM-9999"])},
            "list_my_orders": {},
            "create_support_ticket": {"summary": "Load test ticket " + text[:40], "description": "Simulated customer issue generated by the load test.", "contact_email": "load@example.com"},
        }[name]
        return name, args

    async def complete(self, *, system: str, messages: list[dict[str, Any]], tools: list[dict[str, Any]], static_system_len: int = 0) -> LLMResponse:
        await asyncio.sleep(self.rng.lognormvariate(self.mu, self.sigma))
        last = messages[-1]
        in_tokens = sum(len(str(m["content"])) for m in messages) // 4 + len(system) // 4
        if isinstance(last["content"], str) and self.rng.random() < self.tool_rate:
            name, args = self._pick_tool({t["name"] for t in tools}, last["content"])
            tc = ToolCall(f"toolu_{uuid.uuid4().hex[:10]}", name, args)
            return LLMResponse("", [tc], [{"type": "tool_use", "id": tc.id, "name": tc.name, "input": tc.input}], "tool_use", in_tokens, 60)
        text = "Here is a simulated answer based on our help articles."
        return LLMResponse(text, [], [{"type": "text", "text": text}], "end_turn", in_tokens, 40)
